-- Run this in Supabase Dashboard -> SQL Editor -> New query.
-- This starter setup allows visitors to read notes and anyone with the public
-- website to submit a new note. Do not use it for private/confidential content.
create table if not exists public.love_notes (
  id bigint generated by default as identity primary key,
  sender_name text not null,
  recipient_name text,
  message text not null,
  photo_url text,
  created_at timestamptz not null default now()
);

alter table public.love_notes enable row level security;

drop policy if exists "Anyone can read love notes" on public.love_notes;
create policy "Anyone can read love notes"
on public.love_notes for select
to anon, authenticated
using (true);

drop policy if exists "Anyone can submit a love note" on public.love_notes;
create policy "Anyone can submit a love note"
on public.love_notes for insert
to anon, authenticated
with check (
  char_length(sender_name) between 1 and 50
  and (recipient_name is null or char_length(recipient_name) <= 50)
  and char_length(message) between 1 and 3000
);

-- Create a public bucket for the photo shown on the proposal page.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('love-photos', 'love-photos', true, 5242880, array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set public = true, file_size_limit = 5242880,
  allowed_mime_types = array['image/jpeg','image/png','image/webp'];

drop policy if exists "Public can view love photos" on storage.objects;
create policy "Public can view love photos"
on storage.objects for select
to anon, authenticated
using (bucket_id = 'love-photos');

drop policy if exists "Public can upload love photos" on storage.objects;
create policy "Public can upload love photos"
on storage.objects for insert
to anon, authenticated
with check (bucket_id = 'love-photos' and
  (storage.extension(name) in ('jpg','jpeg','png','webp')));
